import tempfile

def process_audio_gemini(audio_bytes, mime_type, api_key, file_name="uploaded_audio.mp3"):
    """
    Passes raw audio to Google Gemini models for speech-to-text,
    classification, QA scoring, sentiment, and action item extraction.
    Uses temperature=0.0 for deterministic consistency and automatic multilingual detection
    with standardized English output for summaries and action items.
    """
    if not GENAI_AVAILABLE or not api_key:
        return generate_mock_single_record(file_name)

    model_candidates = ['gemini-3.6-flash', 'gemini-2.5-flash-lite', 'gemini-flash-latest', 'gemini-1.5-flash']
    gen_config = {"temperature": 0.0, "top_p": 0.95}
    
    prompt = """
    You are a deterministic, highly precise Call Center Speech Analytics AI Engine.
    Listen to this raw audio recording carefully and extract structured call intelligence.
    
    CRITICAL EXTRACTION RULES:
    1. AUTOMATIC LANGUAGE DETECTION: Detect the primary language spoken in the audio file and record it in "Detected_Language" (e.g., "English", "Spanish", "Hindi", "French", "German", "Mandarin", "Arabic", etc.).
    2. TRANSCRIPT: Provide a verbatim transcript of the audio in "Transcript" (in the original spoken language).
    3. STANDARDIZED ENGLISH OUTPUT: Write the "Summary", "Concerns", "Action_Items", "Classification", and "Primary_Topic" ALWAYS in CLEAR, PROFESSIONAL ENGLISH regardless of the original spoken audio language.
    4. DETERMINISTIC ACCURACY: Be strictly factual and consistent. Extract ONLY explicit customer complaints and promised follow-up action items directly stated in the conversation. Do not hallucinate or invent details.
    
    Return ONLY valid JSON matching this exact structure:
    {
      "Detected_Language": "English",
      "Classification": "Phone Call",
      "Primary_Topic": "Billing",
      "Sentiment": "Positive",
      "Sentiment_Score": 85,
      "CSAT_Score": 4.5,
      "QA_Score": 90,
      "Duration_Sec": 300,
      "Summary": "Concise 2-sentence executive summary of caller query and resolution in English.",
      "Transcript": "Full verbatim transcript of what was spoken in the audio.",
      "Concerns": ["Factual customer complaint 1 in English", "Factual customer complaint 2 in English"],
      "Action_Items": ["Factual follow-up action 1 in English", "Factual follow-up action 2 in English"]
    }
    Do not include markdown codeblocks or extra explanatory text outside the JSON object.
    """

    genai.configure(api_key=api_key)
    last_error = ""

    # Strategy 1: Direct Inline Audio Payload with temperature=0.0
    for model_name in model_candidates:
        try:
            model = genai.GenerativeModel(model_name, generation_config=gen_config)
            response = model.generate_content([
                {"mime_type": mime_type, "data": audio_bytes},
                prompt
            ])
            raw_text = response.text.strip()
            clean_text = re.sub(r'^```json\s*', '', raw_text, flags=re.MULTILINE)
            clean_text = re.sub(r'^```\s*', '', clean_text, flags=re.MULTILINE)
            clean_text = clean_text.strip()

            data = json.loads(clean_text)
            data["File_Name"] = file_name
            data["Call_ID"] = f"CALL-{np.random.randint(1000, 9999)}"
            return data
        except Exception as e:
            last_error = str(e)
            continue

    # Strategy 2: File API payload if direct inline failed
    temp_path = None
    try:
        ext = file_name.split(".")[-1].lower() if "." in file_name else "mp3"
        with tempfile.NamedTemporaryFile(delete=False, suffix=f".{ext}") as tmp:
            tmp.write(audio_bytes)
            temp_path = tmp.name

        audio_file = genai.upload_file(path=temp_path, mime_type=mime_type)
        
        # Wait briefly for file processing if needed
        for _ in range(10):
            if hasattr(audio_file, 'state') and hasattr(audio_file.state, 'name') and audio_file.state.name == "PROCESSING":
                time.sleep(1)
                audio_file = genai.get_file(audio_file.name)
            else:
                break

        for model_name in model_candidates:
            try:
                model = genai.GenerativeModel(model_name, generation_config=gen_config)
                response = model.generate_content([audio_file, prompt])
                raw_text = response.text.strip()
                clean_text = re.sub(r'^```json\s*', '', raw_text, flags=re.MULTILINE)
                clean_text = re.sub(r'^```\s*', '', clean_text, flags=re.MULTILINE)
                clean_text = clean_text.strip()

                data = json.loads(clean_text)
                data["File_Name"] = file_name
                data["Call_ID"] = f"CALL-{np.random.randint(1000, 9999)}"
                return data
            except Exception as e:
                last_error = str(e)
                continue

    except Exception as file_e:
        last_error = str(file_e)

    finally:
        if temp_path and os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except Exception:
                pass

    # If all attempts fail, activate fallback with exact diagnostic note
    fallback = generate_mock_single_record(file_name)
    fallback["Summary"] += f" (Note: Gemini API returned error: {last_error[:70]}... Fallback engine activated)."
    return fallback

