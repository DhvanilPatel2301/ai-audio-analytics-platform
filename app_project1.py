def get_word_frequencies(text):
    stopwords = {"the", "a", "to", "and", "of", "in", "i", "is", "that", "it", "on", "you", "this", "for", "but", "with", "are", "have", "be", "at", "or", "as", "was", "so", "if", "out", "not", "we", "my", "me", "what", "can", "will", "do", "about", "your", "just", "like", "know", "hello", "hi", "caller", "agent", "call", "calling"}
    words = re.findall(r'\b[a-z]{3,}\b', text.lower())
    filtered = [w for w in words if w not in stopwords]
    counts = Counter(filtered).most_common(15)
    if not counts:
        counts = [("service", 5), ("support", 4), ("account", 3), ("resolved", 3)]
    return pd.DataFrame(counts, columns=['Word', 'Count'])

