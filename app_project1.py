def convert_df_to_csv(df):
    return df.to_csv(index=False).encode('utf-8')

def convert_df_to_excel(df):
    output = io.BytesIO()
    with pd.ExcelWriter(output, engine='openpyxl') as writer:
        df.to_excel(writer, sheet_name='Call_Intelligence', index=False)
        
        action_rows = []
        for _, row in df.iterrows():
            items = row.get("Action_Items", [])
            if isinstance(items, list):
                for item in items:
                    action_rows.append({"Call_ID": row.get("Call_ID"), "File_Name": row.get("File_Name"), "Action_Item": item})
            elif isinstance(items, str):
                action_rows.append({"Call_ID": row.get("Call_ID"), "File_Name": row.get("File_Name"), "Action_Item": items})
                
        df_actions = pd.DataFrame(action_rows) if action_rows else pd.DataFrame(columns=["Call_ID", "File_Name", "Action_Item"])
        df_actions.to_excel(writer, sheet_name='Action_Items', index=False)
        
    return output.getvalue()

